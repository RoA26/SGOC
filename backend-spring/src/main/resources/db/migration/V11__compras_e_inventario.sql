-- Fase 2: órdenes de compra, recepciones, existencias y movimientos de inventario.
--
-- Nada se borra ni se reescribe: se añaden tablas, columnas y restricciones. Todas las tablas
-- nuevas llevan empresa_id y FK compuestas (empresa_id, x_id): la base de datos impide que un
-- documento de una empresa apunte a datos de otra, aunque falle la aplicación.
-- SQL válido en PostgreSQL y en H2 (modo PostgreSQL).

-- ---------------------------------------------------------------------------
-- 1) Destinos de las FK compuestas: productos y solicitudes por (empresa_id, id).
-- ---------------------------------------------------------------------------
ALTER TABLE productos ADD CONSTRAINT uq_productos_empresa_id UNIQUE (empresa_id, id);
ALTER TABLE solicitudes ADD CONSTRAINT uq_solicitudes_empresa_id UNIQUE (empresa_id, id);

-- ---------------------------------------------------------------------------
-- 2) detalles_solicitud.empresa_id (riesgo 6 de la Fase 1): la línea, su solicitud y su
--    producto pertenecen a la misma empresa. Se rellena con la empresa de la solicitud; si
--    algún dato antiguo cruzara empresas, la FK compuesta haría fallar la migración (y
--    PostgreSQL la desharía entera) en lugar de conservarlo en silencio.
-- ---------------------------------------------------------------------------
ALTER TABLE detalles_solicitud ADD COLUMN empresa_id BIGINT;
UPDATE detalles_solicitud
SET empresa_id = (SELECT s.empresa_id FROM solicitudes s WHERE s.id = detalles_solicitud.solicitud_id);
ALTER TABLE detalles_solicitud ALTER COLUMN empresa_id SET NOT NULL;

ALTER TABLE detalles_solicitud DROP CONSTRAINT fk_detalles_solicitud_solicitud;
ALTER TABLE detalles_solicitud ADD CONSTRAINT fk_detalles_solicitud_solicitud
    FOREIGN KEY (empresa_id, solicitud_id) REFERENCES solicitudes (empresa_id, id) ON DELETE CASCADE;
ALTER TABLE detalles_solicitud DROP CONSTRAINT fk_detalles_solicitud_producto;
ALTER TABLE detalles_solicitud ADD CONSTRAINT fk_detalles_solicitud_producto
    FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id);

-- ---------------------------------------------------------------------------
-- 3) productos.stock_minimo: por debajo (o igual) el producto está en stock crítico.
--    0 = sin mínimo definido. Los productos existentes empiezan en 0.
-- ---------------------------------------------------------------------------
ALTER TABLE productos ADD COLUMN stock_minimo INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE productos ADD CONSTRAINT ck_productos_stock_minimo CHECK (stock_minimo BETWEEN 0 AND 999999);

-- ---------------------------------------------------------------------------
-- 4) Órdenes de compra (cabecera). Estados:
--    BORRADOR → EMITIDA → RECIBIDA_PARCIALMENTE → RECIBIDA, y CANCELADA desde BORRADOR o
--    EMITIDA (sin recepciones). El número es correlativo por empresa.
-- ---------------------------------------------------------------------------
CREATE TABLE ordenes_compra (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id          BIGINT        NOT NULL,
    numero              BIGINT        NOT NULL,
    proveedor_id        BIGINT        NOT NULL,
    -- Solicitud aprobada de la que procede (opcional).
    solicitud_id        BIGINT,
    estado              VARCHAR(25)   NOT NULL DEFAULT 'BORRADOR',
    observaciones       VARCHAR(1000),
    creado_por_id       BIGINT        NOT NULL,
    creado_en           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    emitida_por_id      BIGINT,
    emitida_en          TIMESTAMP WITH TIME ZONE,
    cancelada_por_id    BIGINT,
    cancelada_en        TIMESTAMP WITH TIME ZONE,
    motivo_cancelacion  VARCHAR(500),

    CONSTRAINT pk_ordenes_compra PRIMARY KEY (id),
    CONSTRAINT uq_ordenes_compra_numero UNIQUE (empresa_id, numero),
    CONSTRAINT uq_ordenes_compra_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_ordenes_compra_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_ordenes_compra_proveedor
        FOREIGN KEY (empresa_id, proveedor_id) REFERENCES proveedores (empresa_id, id),
    CONSTRAINT fk_ordenes_compra_solicitud
        FOREIGN KEY (empresa_id, solicitud_id) REFERENCES solicitudes (empresa_id, id),
    -- Quien crea, emite o cancela es una persona de la misma empresa.
    CONSTRAINT fk_ordenes_compra_creado_por
        FOREIGN KEY (empresa_id, creado_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT fk_ordenes_compra_emitida_por
        FOREIGN KEY (empresa_id, emitida_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT fk_ordenes_compra_cancelada_por
        FOREIGN KEY (empresa_id, cancelada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_ordenes_compra_numero CHECK (numero > 0),
    CONSTRAINT ck_ordenes_compra_estado
        CHECK (estado IN ('BORRADOR', 'EMITIDA', 'RECIBIDA_PARCIALMENTE', 'RECIBIDA', 'CANCELADA')),
    -- Emitida: siempre con quién y cuándo; un borrador, nunca.
    CONSTRAINT ck_ordenes_compra_emision CHECK (
        (emitida_en IS NULL AND emitida_por_id IS NULL AND estado IN ('BORRADOR', 'CANCELADA'))
        OR (emitida_en IS NOT NULL AND emitida_por_id IS NOT NULL AND estado <> 'BORRADOR')),
    -- Cancelada: siempre con quién, cuándo y por qué; las demás, nunca.
    CONSTRAINT ck_ordenes_compra_cancelacion CHECK (
        (estado = 'CANCELADA' AND cancelada_en IS NOT NULL AND cancelada_por_id IS NOT NULL
            AND motivo_cancelacion IS NOT NULL)
        OR (estado <> 'CANCELADA' AND cancelada_en IS NULL AND cancelada_por_id IS NULL
            AND motivo_cancelacion IS NULL))
);

CREATE INDEX ix_ordenes_compra_empresa_estado ON ordenes_compra (empresa_id, estado);
CREATE INDEX ix_ordenes_compra_empresa_emitida ON ordenes_compra (empresa_id, emitida_en);
-- Analítica global (todas las empresas) por fecha de emisión.
CREATE INDEX ix_ordenes_compra_emitida ON ordenes_compra (emitida_en);
CREATE INDEX ix_ordenes_compra_proveedor ON ordenes_compra (empresa_id, proveedor_id);
CREATE INDEX ix_ordenes_compra_solicitud ON ordenes_compra (empresa_id, solicitud_id);

-- ---------------------------------------------------------------------------
-- 5) Líneas de la orden: producto, cantidad pedida, costo unitario pactado y lo recibido.
-- ---------------------------------------------------------------------------
CREATE TABLE detalles_orden_compra (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id         BIGINT         NOT NULL,
    orden_id           BIGINT         NOT NULL,
    producto_id        BIGINT         NOT NULL,
    cantidad           INTEGER        NOT NULL,
    costo_unitario     NUMERIC(14, 2) NOT NULL,
    cantidad_recibida  INTEGER        DEFAULT 0 NOT NULL,

    CONSTRAINT pk_detalles_orden_compra PRIMARY KEY (id),
    -- Un producto aparece una sola vez por orden.
    CONSTRAINT uq_detalles_orden_compra_producto UNIQUE (orden_id, producto_id),
    CONSTRAINT uq_detalles_orden_compra_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_detalles_orden_compra_orden
        FOREIGN KEY (empresa_id, orden_id) REFERENCES ordenes_compra (empresa_id, id),
    CONSTRAINT fk_detalles_orden_compra_producto
        FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id),
    CONSTRAINT ck_detalles_orden_compra_cantidad CHECK (cantidad BETWEEN 1 AND 999999),
    CONSTRAINT ck_detalles_orden_compra_costo CHECK (costo_unitario > 0),
    -- Nunca se recibe más de lo pedido.
    CONSTRAINT ck_detalles_orden_compra_recibida CHECK (cantidad_recibida BETWEEN 0 AND cantidad)
);

CREATE INDEX ix_detalles_orden_compra_producto ON detalles_orden_compra (producto_id);

-- ---------------------------------------------------------------------------
-- 6) Recepciones (parciales o totales) de una orden emitida. La clave de idempotencia la
--    genera el cliente: repetir la misma petición no registra dos veces la mercancía.
-- ---------------------------------------------------------------------------
CREATE TABLE recepciones (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id          BIGINT       NOT NULL,
    orden_id            BIGINT       NOT NULL,
    clave_idempotencia  VARCHAR(64)  NOT NULL,
    recibida_por_id     BIGINT       NOT NULL,
    recibida_en         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones       VARCHAR(500),

    CONSTRAINT pk_recepciones PRIMARY KEY (id),
    CONSTRAINT uq_recepciones_clave UNIQUE (empresa_id, clave_idempotencia),
    CONSTRAINT uq_recepciones_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_recepciones_orden FOREIGN KEY (empresa_id, orden_id) REFERENCES ordenes_compra (empresa_id, id),
    CONSTRAINT fk_recepciones_recibida_por
        FOREIGN KEY (empresa_id, recibida_por_id) REFERENCES usuarios (empresa_id, id)
);

CREATE INDEX ix_recepciones_orden ON recepciones (empresa_id, orden_id);
CREATE INDEX ix_recepciones_empresa_fecha ON recepciones (empresa_id, recibida_en);

CREATE TABLE detalles_recepcion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id        BIGINT  NOT NULL,
    recepcion_id      BIGINT  NOT NULL,
    detalle_orden_id  BIGINT  NOT NULL,
    cantidad          INTEGER NOT NULL,

    CONSTRAINT pk_detalles_recepcion PRIMARY KEY (id),
    CONSTRAINT uq_detalles_recepcion_linea UNIQUE (recepcion_id, detalle_orden_id),
    CONSTRAINT uq_detalles_recepcion_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_detalles_recepcion_recepcion
        FOREIGN KEY (empresa_id, recepcion_id) REFERENCES recepciones (empresa_id, id),
    CONSTRAINT fk_detalles_recepcion_detalle_orden
        FOREIGN KEY (empresa_id, detalle_orden_id) REFERENCES detalles_orden_compra (empresa_id, id),
    CONSTRAINT ck_detalles_recepcion_cantidad CHECK (cantidad BETWEEN 1 AND 999999)
);

CREATE INDEX ix_detalles_recepcion_detalle_orden ON detalles_recepcion (detalle_orden_id);

-- ---------------------------------------------------------------------------
-- 7) Existencias: una fila por producto, con el saldo actual. Se bloquea (FOR UPDATE) en
--    cada movimiento, así que dos operaciones simultáneas sobre el mismo producto se
--    serializan. Los productos existentes empiezan con 0 unidades.
-- ---------------------------------------------------------------------------
CREATE TABLE existencias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id      BIGINT  NOT NULL,
    producto_id     BIGINT  NOT NULL,
    cantidad        INTEGER DEFAULT 0 NOT NULL,
    actualizado_en  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_existencias PRIMARY KEY (id),
    CONSTRAINT uq_existencias_producto UNIQUE (producto_id),
    CONSTRAINT fk_existencias_producto FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id),
    CONSTRAINT ck_existencias_cantidad CHECK (cantidad >= 0)
);

CREATE INDEX ix_existencias_empresa ON existencias (empresa_id);

INSERT INTO existencias (empresa_id, producto_id, cantidad)
SELECT empresa_id, id, 0 FROM productos;

-- ---------------------------------------------------------------------------
-- 8) Movimientos de inventario (kárdex): cada cambio de existencias deja una fila con quién,
--    cuándo, cuánto, el saldo resultante y su origen. No se modifican ni se borran.
--    RECEPCION: entrada por una línea de recepción, con el costo de la orden.
--    AJUSTE: corrección manual (inventario inicial, conteo, merma) con motivo obligatorio.
--    Las ventas (POS) añadirán su propio tipo en una migración posterior.
-- ---------------------------------------------------------------------------
CREATE TABLE movimientos_inventario (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id            BIGINT         NOT NULL,
    producto_id           BIGINT         NOT NULL,
    tipo                  VARCHAR(20)    NOT NULL,
    -- Con signo: positiva entra, negativa sale.
    cantidad              INTEGER        NOT NULL,
    saldo_resultante      INTEGER        NOT NULL,
    costo_unitario        NUMERIC(14, 2),
    detalle_recepcion_id  BIGINT,
    motivo                VARCHAR(300),
    clave_idempotencia    VARCHAR(64),
    usuario_id            BIGINT         NOT NULL,
    fecha                 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_movimientos_inventario PRIMARY KEY (id),
    CONSTRAINT uq_movimientos_inventario_clave UNIQUE (empresa_id, clave_idempotencia),
    CONSTRAINT uq_movimientos_inventario_detalle_recepcion UNIQUE (detalle_recepcion_id),
    CONSTRAINT fk_movimientos_inventario_producto
        FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id),
    CONSTRAINT fk_movimientos_inventario_detalle_recepcion
        FOREIGN KEY (empresa_id, detalle_recepcion_id) REFERENCES detalles_recepcion (empresa_id, id),
    CONSTRAINT fk_movimientos_inventario_usuario
        FOREIGN KEY (empresa_id, usuario_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_movimientos_inventario_tipo CHECK (tipo IN ('RECEPCION', 'AJUSTE')),
    CONSTRAINT ck_movimientos_inventario_cantidad CHECK (cantidad <> 0 AND cantidad BETWEEN -999999 AND 999999),
    CONSTRAINT ck_movimientos_inventario_saldo CHECK (saldo_resultante >= 0),
    CONSTRAINT ck_movimientos_inventario_costo CHECK (costo_unitario IS NULL OR costo_unitario > 0),
    CONSTRAINT ck_movimientos_inventario_origen CHECK (
        (tipo = 'RECEPCION' AND detalle_recepcion_id IS NOT NULL AND cantidad > 0 AND costo_unitario IS NOT NULL)
        OR (tipo = 'AJUSTE' AND detalle_recepcion_id IS NULL AND motivo IS NOT NULL
            AND clave_idempotencia IS NOT NULL))
);

CREATE INDEX ix_movimientos_inventario_producto ON movimientos_inventario (empresa_id, producto_id, fecha);
CREATE INDEX ix_movimientos_inventario_fecha ON movimientos_inventario (empresa_id, fecha);
