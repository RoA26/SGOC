-- Fase 3: documento de la orden emitida, programación de entregas e incidencias de recepción.
--
-- No destructiva: solo añade tablas, una columna nula y restricciones. Ningún dato existente
-- cambia. Mismas convenciones que V11: empresa_id en todas las tablas y FK compuestas
-- (empresa_id, x_id) para que la BD impida cruzar datos entre empresas.
-- SQL válido en PostgreSQL y en H2 (modo PostgreSQL).

-- ---------------------------------------------------------------------------
-- 1) Documento de la orden: instantánea inmutable de lo que se emitió (empresa compradora,
--    proveedor, entrega, líneas y totales) en JSON, con su huella SHA-256. El .docx se genera
--    a partir de ella en cada descarga: no se guardan binarios y el documento no cambia aunque
--    después cambien el catálogo, el proveedor o la empresa. Versión 1 = la emisión; la columna
--    admite versiones posteriores si algún día existe un proceso de modificación de órdenes
--    emitidas (hoy no existe: una orden emitida no se edita).
--    Las órdenes emitidas antes de V13 no tienen fila: su documento se reconstruye al
--    descargarlo y lo indica en el propio documento.
-- ---------------------------------------------------------------------------
CREATE TABLE documentos_orden_compra (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id       BIGINT         NOT NULL,
    orden_id         BIGINT         NOT NULL,
    version          INTEGER        NOT NULL,
    motivo           VARCHAR(20)    NOT NULL,
    contenido        VARCHAR(200000) NOT NULL,
    huella_sha256    VARCHAR(64)    NOT NULL,
    generado_por_id  BIGINT         NOT NULL,
    generado_en      TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_documentos_orden_compra PRIMARY KEY (id),
    CONSTRAINT uq_documentos_orden_compra_version UNIQUE (orden_id, version),
    CONSTRAINT fk_documentos_orden_compra_orden
        FOREIGN KEY (empresa_id, orden_id) REFERENCES ordenes_compra (empresa_id, id),
    CONSTRAINT fk_documentos_orden_compra_generado_por
        FOREIGN KEY (empresa_id, generado_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_documentos_orden_compra_version CHECK (version > 0),
    CONSTRAINT ck_documentos_orden_compra_motivo CHECK (motivo IN ('EMISION'))
);

-- ---------------------------------------------------------------------------
-- 2) Programación de la entrega: historial de solo inserción. Cada cambio (programar,
--    reprogramar, confirmar con el proveedor) es una fila nueva con su versión, quién, cuándo
--    y, desde la segunda, el motivo. La orden apunta a la vigente; el calendario usa esa y el
--    historial conserva las anteriores.
--    fecha_estimada es una fecha (sin hora). La franja es opcional: sin ella, la entrega es
--    "todo el día". confirmada_proveedor distingue lo que el gerente estima de lo que el
--    proveedor confirmó. Nada de esto es la recepción real (recepciones.recibida_en).
-- ---------------------------------------------------------------------------
CREATE TABLE programaciones_entrega (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id            BIGINT        NOT NULL,
    orden_id              BIGINT        NOT NULL,
    version               INTEGER       NOT NULL,
    fecha_estimada        DATE          NOT NULL,
    hora_desde            TIME,
    hora_hasta            TIME,
    confirmada_proveedor  BOOLEAN       DEFAULT FALSE NOT NULL,
    referencia_proveedor  VARCHAR(60),
    observaciones         VARCHAR(500),
    motivo_cambio         VARCHAR(300),
    registrada_por_id     BIGINT        NOT NULL,
    registrada_en         TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_programaciones_entrega PRIMARY KEY (id),
    CONSTRAINT uq_programaciones_entrega_version UNIQUE (orden_id, version),
    -- Destino de la FK de la orden: la vigente debe ser una programación de esa misma orden.
    CONSTRAINT uq_programaciones_entrega_orden_id UNIQUE (empresa_id, orden_id, id),
    CONSTRAINT fk_programaciones_entrega_orden
        FOREIGN KEY (empresa_id, orden_id) REFERENCES ordenes_compra (empresa_id, id),
    CONSTRAINT fk_programaciones_entrega_registrada_por
        FOREIGN KEY (empresa_id, registrada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_programaciones_entrega_version CHECK (version > 0),
    CONSTRAINT ck_programaciones_entrega_franja CHECK (
        (hora_desde IS NULL AND hora_hasta IS NULL)
        OR (hora_desde IS NOT NULL AND hora_hasta IS NOT NULL AND hora_desde < hora_hasta)),
    -- Reprogramar exige explicar por qué.
    CONSTRAINT ck_programaciones_entrega_motivo CHECK (version = 1 OR motivo_cambio IS NOT NULL)
);

CREATE INDEX ix_programaciones_entrega_fecha ON programaciones_entrega (empresa_id, fecha_estimada);

ALTER TABLE ordenes_compra ADD COLUMN programacion_entrega_id BIGINT;
ALTER TABLE ordenes_compra ADD CONSTRAINT fk_ordenes_compra_programacion
    FOREIGN KEY (empresa_id, id, programacion_entrega_id)
    REFERENCES programaciones_entrega (empresa_id, orden_id, id);

-- ---------------------------------------------------------------------------
-- 3) Incidencias de una recepción: faltantes, unidades dañadas, excedentes (no se aceptan en
--    el inventario), productos incorrectos y otras novedades. Son informativas: ninguna mueve
--    existencias; solo lo aceptado (detalles_recepcion) entra al inventario. Como la
--    recepción, son hechos: no se modifican.
-- ---------------------------------------------------------------------------
CREATE TABLE incidencias_recepcion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id        BIGINT        NOT NULL,
    recepcion_id      BIGINT        NOT NULL,
    detalle_orden_id  BIGINT,
    tipo              VARCHAR(25)   NOT NULL,
    cantidad          INTEGER,
    descripcion       VARCHAR(500),

    CONSTRAINT pk_incidencias_recepcion PRIMARY KEY (id),
    CONSTRAINT fk_incidencias_recepcion_recepcion
        FOREIGN KEY (empresa_id, recepcion_id) REFERENCES recepciones (empresa_id, id),
    CONSTRAINT fk_incidencias_recepcion_detalle_orden
        FOREIGN KEY (empresa_id, detalle_orden_id) REFERENCES detalles_orden_compra (empresa_id, id),
    CONSTRAINT ck_incidencias_recepcion_tipo
        CHECK (tipo IN ('FALTANTE', 'DANADO', 'EXCEDENTE', 'PRODUCTO_INCORRECTO', 'OTRO')),
    CONSTRAINT ck_incidencias_recepcion_cantidad CHECK (cantidad IS NULL OR cantidad BETWEEN 1 AND 999999),
    -- Por línea y con cantidad: faltante, dañado y excedente. Con descripción: incorrecto y otro.
    CONSTRAINT ck_incidencias_recepcion_datos CHECK (
        (tipo IN ('FALTANTE', 'DANADO', 'EXCEDENTE') AND detalle_orden_id IS NOT NULL AND cantidad IS NOT NULL)
        OR (tipo IN ('PRODUCTO_INCORRECTO', 'OTRO') AND descripcion IS NOT NULL))
);

CREATE INDEX ix_incidencias_recepcion_recepcion ON incidencias_recepcion (empresa_id, recepcion_id);
