-- Módulo comercial: precio de venta y tratamiento del IVA por producto, historial de cambios de
-- condiciones de venta, política comercial por empresa, autorizaciones de excepción, ventas
-- (líneas, pagos), devoluciones y anulaciones, y el costo promedio de las existencias.
--
-- Nada se borra ni se reescribe: solo se añaden columnas, tablas y restricciones. Los productos
-- existentes quedan SIN precio de venta y SIN clasificación del IVA (no se pueden vender hasta que
-- el administrador comercial los defina): no se presume ninguna tarifa. productos.precio conserva
-- su significado (precio de referencia de compra de solicitudes y órdenes).
-- Toda tabla nueva lleva empresa_id y FK compuestas (empresa_id, x_id): la base de datos impide
-- cruzar empresas aunque falle la aplicación. SQL válido en PostgreSQL y en H2 (modo PostgreSQL).

-- ---------------------------------------------------------------------------
-- 1) Empresas de demostración: marca explícita para la seed de desarrollo (nunca se aplica a
--    una empresa existente).
-- ---------------------------------------------------------------------------
ALTER TABLE empresas ADD COLUMN demo BOOLEAN DEFAULT FALSE NOT NULL;

-- ---------------------------------------------------------------------------
-- 2) Condiciones de venta del producto.
--    precio_venta: precio unitario SIN IVA (el IVA se calcula sobre la base, después de los
--    descuentos). tratamiento_iva: GRAVADO (tarifa > 0, p. ej. 19 o 5), EXENTO (gravado a
--    tarifa 0) o EXCLUIDO (no causa IVA). Una tarifa cero no se confunde con un exento o un
--    excluido: el tratamiento se guarda aparte.
-- ---------------------------------------------------------------------------
ALTER TABLE productos ADD COLUMN precio_venta NUMERIC(14, 2);
ALTER TABLE productos ADD COLUMN tratamiento_iva VARCHAR(12);
ALTER TABLE productos ADD COLUMN tarifa_iva NUMERIC(5, 2);
ALTER TABLE productos ADD CONSTRAINT ck_productos_precio_venta CHECK (precio_venta IS NULL OR precio_venta > 0);
ALTER TABLE productos ADD CONSTRAINT ck_productos_iva CHECK (
    (tratamiento_iva IS NULL AND tarifa_iva IS NULL)
    OR (tratamiento_iva = 'GRAVADO' AND tarifa_iva > 0 AND tarifa_iva < 100)
    OR (tratamiento_iva IN ('EXENTO', 'EXCLUIDO') AND tarifa_iva = 0));
-- Solo se vende con el IVA clasificado.
ALTER TABLE productos ADD CONSTRAINT ck_productos_venta_clasificada
    CHECK (precio_venta IS NULL OR tratamiento_iva IS NOT NULL);

-- ---------------------------------------------------------------------------
-- 3) Historial de condiciones de venta (solo inserción): cada cambio de precio o de IVA, con
--    los valores anteriores y nuevos, quién, cuándo y por qué. Nunca se modifica.
-- ---------------------------------------------------------------------------
CREATE TABLE cambios_precio (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id            BIGINT         NOT NULL,
    producto_id           BIGINT         NOT NULL,
    precio_anterior       NUMERIC(14, 2),
    precio_nuevo          NUMERIC(14, 2) NOT NULL,
    tratamiento_anterior  VARCHAR(12),
    tratamiento_nuevo     VARCHAR(12)    NOT NULL,
    tarifa_anterior       NUMERIC(5, 2),
    tarifa_nueva          NUMERIC(5, 2)  NOT NULL,
    -- Costo promedio del producto en el momento del cambio (referencia; puede ser desconocido).
    costo_referencia      NUMERIC(14, 4),
    motivo                VARCHAR(300),
    usuario_id            BIGINT         NOT NULL,
    fecha                 TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_cambios_precio PRIMARY KEY (id),
    CONSTRAINT fk_cambios_precio_producto FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id),
    CONSTRAINT fk_cambios_precio_usuario FOREIGN KEY (empresa_id, usuario_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_cambios_precio_precio CHECK (precio_nuevo > 0 AND (precio_anterior IS NULL OR precio_anterior > 0))
);

CREATE INDEX ix_cambios_precio_producto ON cambios_precio (empresa_id, producto_id, fecha);
CREATE INDEX ix_cambios_precio_fecha ON cambios_precio (empresa_id, fecha);

-- ---------------------------------------------------------------------------
-- 4) Política comercial de la empresa (una fila por empresa; sin fila rigen los valores por
--    defecto del código: el trabajador no puede descontar y las ventas bajo el costo se permiten
--    con advertencia).
-- ---------------------------------------------------------------------------
CREATE TABLE politicas_comerciales (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id                   BIGINT        NOT NULL,
    descuento_max_trabajador     NUMERIC(5, 2) NOT NULL,
    descuento_max_administrador  NUMERIC(5, 2) NOT NULL,
    -- PERMITIR: se vende con advertencia. AUTORIZACION: exige una autorización de excepción.
    venta_bajo_costo             VARCHAR(15)   NOT NULL,
    -- Margen bruto objetivo para sugerir precios (nunca cambia un precio por sí solo).
    margen_objetivo              NUMERIC(5, 2),
    actualizada_por_id           BIGINT        NOT NULL,
    actualizada_en               TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_politicas_comerciales PRIMARY KEY (id),
    CONSTRAINT uq_politicas_comerciales_empresa UNIQUE (empresa_id),
    CONSTRAINT fk_politicas_comerciales_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_politicas_comerciales_usuario
        FOREIGN KEY (empresa_id, actualizada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_politicas_comerciales_descuentos CHECK (
        descuento_max_trabajador BETWEEN 0 AND 100 AND descuento_max_administrador BETWEEN 0 AND 100
        AND descuento_max_trabajador <= descuento_max_administrador),
    CONSTRAINT ck_politicas_comerciales_bajo_costo CHECK (venta_bajo_costo IN ('PERMITIR', 'AUTORIZACION')),
    CONSTRAINT ck_politicas_comerciales_margen CHECK (margen_objetivo IS NULL OR (margen_objetivo >= 0 AND margen_objetivo < 100))
);

-- ---------------------------------------------------------------------------
-- 5) Ventas (cabecera). Inmutables salvo el estado (devoluciones y anulación, que dejan su
--    propio registro). Los importes son los calculados por el servidor al confirmar.
-- ---------------------------------------------------------------------------
CREATE TABLE ventas (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id               BIGINT         NOT NULL,
    numero                   BIGINT         NOT NULL,
    estado                   VARCHAR(25)    NOT NULL,
    clave_idempotencia       VARCHAR(64)    NOT NULL,
    -- SHA-256 de la petición normalizada: la misma clave con otros datos es un conflicto.
    huella_solicitud         VARCHAR(64)    NOT NULL,
    cliente_nombre           VARCHAR(150),
    cliente_documento        VARCHAR(20),
    descuento_general_tipo   VARCHAR(10),
    descuento_general_valor  NUMERIC(14, 2),
    subtotal                 NUMERIC(14, 2) NOT NULL,
    descuento_lineas         NUMERIC(14, 2) NOT NULL,
    descuento_general        NUMERIC(14, 2) NOT NULL,
    base_gravable            NUMERIC(14, 2) NOT NULL,
    impuestos                NUMERIC(14, 2) NOT NULL,
    total                    NUMERIC(14, 2) NOT NULL,
    -- Costo de lo vendido con los costos históricos de las líneas; NULL si alguna línea no lo tiene.
    costo_total              NUMERIC(14, 2),
    autorizacion_id          BIGINT,
    vendida_por_id           BIGINT         NOT NULL,
    vendida_en               TIMESTAMP WITH TIME ZONE NOT NULL,
    anulada_por_id           BIGINT,
    anulada_en               TIMESTAMP WITH TIME ZONE,
    motivo_anulacion         VARCHAR(300),

    CONSTRAINT pk_ventas PRIMARY KEY (id),
    CONSTRAINT uq_ventas_numero UNIQUE (empresa_id, numero),
    CONSTRAINT uq_ventas_clave UNIQUE (empresa_id, clave_idempotencia),
    CONSTRAINT uq_ventas_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_ventas_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
    CONSTRAINT fk_ventas_vendida_por FOREIGN KEY (empresa_id, vendida_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT fk_ventas_anulada_por FOREIGN KEY (empresa_id, anulada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_ventas_numero CHECK (numero > 0),
    CONSTRAINT ck_ventas_estado CHECK (estado IN ('CONFIRMADA', 'DEVUELTA_PARCIALMENTE', 'DEVUELTA', 'ANULADA')),
    CONSTRAINT ck_ventas_importes CHECK (
        subtotal >= 0 AND descuento_lineas >= 0 AND descuento_general >= 0 AND base_gravable >= 0
        AND impuestos >= 0 AND total >= 0
        AND base_gravable = subtotal - descuento_lineas - descuento_general
        AND total = base_gravable + impuestos
        AND (costo_total IS NULL OR costo_total >= 0)),
    CONSTRAINT ck_ventas_descuento_general CHECK (
        (descuento_general_tipo IS NULL AND descuento_general_valor IS NULL)
        OR (descuento_general_tipo IN ('PORCENTAJE', 'VALOR') AND descuento_general_valor > 0)),
    CONSTRAINT ck_ventas_anulacion CHECK (
        (estado = 'ANULADA' AND anulada_por_id IS NOT NULL AND anulada_en IS NOT NULL AND motivo_anulacion IS NOT NULL)
        OR (estado <> 'ANULADA' AND anulada_por_id IS NULL AND anulada_en IS NULL AND motivo_anulacion IS NULL))
);

CREATE INDEX ix_ventas_empresa_fecha ON ventas (empresa_id, vendida_en);
CREATE INDEX ix_ventas_vendedor ON ventas (empresa_id, vendida_por_id, vendida_en);

-- ---------------------------------------------------------------------------
-- 6) Líneas de venta: copia histórica de todo lo aplicado (precio, descuentos, tratamiento y
--    tarifa del IVA, base, impuesto, total y costo). No dependen del catálogo vigente.
--    Orden de cálculo: subtotal = precio × cantidad; − descuento de línea; − parte del
--    descuento general; = base; impuesto = base × tarifa; total = base + impuesto.
-- ---------------------------------------------------------------------------
CREATE TABLE detalles_venta (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id          BIGINT         NOT NULL,
    venta_id            BIGINT         NOT NULL,
    linea               INTEGER        NOT NULL,
    producto_id         BIGINT         NOT NULL,
    sku                 VARCHAR(40)    NOT NULL,
    nombre              VARCHAR(150)   NOT NULL,
    cantidad            INTEGER        NOT NULL,
    precio_unitario     NUMERIC(14, 2) NOT NULL,
    descuento_tipo      VARCHAR(10),
    descuento_valor     NUMERIC(14, 2),
    subtotal            NUMERIC(14, 2) NOT NULL,
    descuento_linea     NUMERIC(14, 2) NOT NULL,
    descuento_general   NUMERIC(14, 2) NOT NULL,
    base_gravable       NUMERIC(14, 2) NOT NULL,
    tratamiento_iva     VARCHAR(12)    NOT NULL,
    tarifa_iva          NUMERIC(5, 2)  NOT NULL,
    impuesto            NUMERIC(14, 2) NOT NULL,
    total               NUMERIC(14, 2) NOT NULL,
    -- Costo unitario histórico (método en metodo_costo); NULL = desconocido, nunca 0 inventado.
    costo_unitario      NUMERIC(14, 4),
    metodo_costo        VARCHAR(25)    NOT NULL,
    bajo_costo          BOOLEAN        NOT NULL,
    cantidad_devuelta   INTEGER        DEFAULT 0 NOT NULL,

    CONSTRAINT pk_detalles_venta PRIMARY KEY (id),
    CONSTRAINT uq_detalles_venta_linea UNIQUE (venta_id, linea),
    CONSTRAINT uq_detalles_venta_producto UNIQUE (venta_id, producto_id),
    CONSTRAINT uq_detalles_venta_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_detalles_venta_venta FOREIGN KEY (empresa_id, venta_id) REFERENCES ventas (empresa_id, id),
    CONSTRAINT fk_detalles_venta_producto FOREIGN KEY (empresa_id, producto_id) REFERENCES productos (empresa_id, id),
    CONSTRAINT ck_detalles_venta_cantidad CHECK (cantidad BETWEEN 1 AND 999999),
    CONSTRAINT ck_detalles_venta_devuelta CHECK (cantidad_devuelta BETWEEN 0 AND cantidad),
    CONSTRAINT ck_detalles_venta_importes CHECK (
        precio_unitario > 0 AND subtotal > 0 AND descuento_linea >= 0 AND descuento_general >= 0
        AND base_gravable >= 0 AND impuesto >= 0
        AND base_gravable = subtotal - descuento_linea - descuento_general
        AND total = base_gravable + impuesto),
    CONSTRAINT ck_detalles_venta_descuento CHECK (
        (descuento_tipo IS NULL AND descuento_valor IS NULL)
        OR (descuento_tipo IN ('PORCENTAJE', 'VALOR') AND descuento_valor > 0)),
    CONSTRAINT ck_detalles_venta_iva CHECK (
        (tratamiento_iva = 'GRAVADO' AND tarifa_iva > 0 AND tarifa_iva < 100)
        OR (tratamiento_iva IN ('EXENTO', 'EXCLUIDO') AND tarifa_iva = 0)),
    CONSTRAINT ck_detalles_venta_costo CHECK (
        (costo_unitario IS NULL AND metodo_costo = 'DESCONOCIDO')
        OR (costo_unitario > 0 AND metodo_costo = 'PROMEDIO_PONDERADO'))
);

CREATE INDEX ix_detalles_venta_producto ON detalles_venta (empresa_id, producto_id);

-- ---------------------------------------------------------------------------
-- 7) Pagos de la venta. La suma de los valores es el total; en efectivo se registra además lo
--    recibido y el cambio. Sin pasarelas: es un registro de lo que ocurrió en la caja.
-- ---------------------------------------------------------------------------
CREATE TABLE pagos_venta (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id  BIGINT         NOT NULL,
    venta_id    BIGINT         NOT NULL,
    medio       VARCHAR(20)    NOT NULL,
    valor       NUMERIC(14, 2) NOT NULL,
    recibido    NUMERIC(14, 2),
    cambio      NUMERIC(14, 2),
    referencia  VARCHAR(60),

    CONSTRAINT pk_pagos_venta PRIMARY KEY (id),
    CONSTRAINT fk_pagos_venta_venta FOREIGN KEY (empresa_id, venta_id) REFERENCES ventas (empresa_id, id),
    CONSTRAINT ck_pagos_venta_medio CHECK (medio IN ('EFECTIVO', 'TARJETA_DEBITO', 'TARJETA_CREDITO', 'TRANSFERENCIA', 'OTRO')),
    CONSTRAINT ck_pagos_venta_valor CHECK (valor > 0),
    CONSTRAINT ck_pagos_venta_efectivo CHECK (
        (medio = 'EFECTIVO' AND recibido IS NOT NULL AND recibido >= valor AND cambio = recibido - valor)
        OR (medio <> 'EFECTIVO' AND recibido IS NULL AND cambio IS NULL))
);

CREATE INDEX ix_pagos_venta_venta ON pagos_venta (empresa_id, venta_id);

-- ---------------------------------------------------------------------------
-- 8) Autorizaciones de excepción: código de un solo uso que el administrador comercial entrega
--    para una venta que supera el límite de descuento del vendedor o queda bajo el costo.
-- ---------------------------------------------------------------------------
CREATE TABLE autorizaciones_comerciales (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id          BIGINT        NOT NULL,
    codigo              VARCHAR(32)   NOT NULL,
    descuento_maximo    NUMERIC(5, 2) NOT NULL,
    permite_bajo_costo  BOOLEAN       NOT NULL,
    motivo              VARCHAR(300)  NOT NULL,
    creada_por_id       BIGINT        NOT NULL,
    creada_en           TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_en           TIMESTAMP WITH TIME ZONE NOT NULL,
    venta_id            BIGINT,
    usada_por_id        BIGINT,
    usada_en            TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_autorizaciones_comerciales PRIMARY KEY (id),
    CONSTRAINT uq_autorizaciones_comerciales_codigo UNIQUE (empresa_id, codigo),
    CONSTRAINT uq_autorizaciones_comerciales_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT uq_autorizaciones_comerciales_venta UNIQUE (venta_id),
    CONSTRAINT fk_autorizaciones_comerciales_creada_por
        FOREIGN KEY (empresa_id, creada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT fk_autorizaciones_comerciales_usada_por
        FOREIGN KEY (empresa_id, usada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT fk_autorizaciones_comerciales_venta FOREIGN KEY (empresa_id, venta_id) REFERENCES ventas (empresa_id, id),
    CONSTRAINT ck_autorizaciones_comerciales_descuento CHECK (descuento_maximo BETWEEN 0 AND 100),
    CONSTRAINT ck_autorizaciones_comerciales_vigencia CHECK (expira_en > creada_en),
    CONSTRAINT ck_autorizaciones_comerciales_uso CHECK (
        (venta_id IS NULL AND usada_por_id IS NULL AND usada_en IS NULL)
        OR (venta_id IS NOT NULL AND usada_por_id IS NOT NULL AND usada_en IS NOT NULL))
);

ALTER TABLE ventas ADD CONSTRAINT fk_ventas_autorizacion
    FOREIGN KEY (empresa_id, autorizacion_id) REFERENCES autorizaciones_comerciales (empresa_id, id);

-- ---------------------------------------------------------------------------
-- 9) Devoluciones y anulaciones: registro propio, nunca se borran líneas ni movimientos.
--    Cada línea indica si la unidad vuelve al inventario vendible (reingresa) o no (dañada).
-- ---------------------------------------------------------------------------
CREATE TABLE devoluciones_venta (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id          BIGINT         NOT NULL,
    venta_id            BIGINT         NOT NULL,
    tipo                VARCHAR(12)    NOT NULL,
    clave_idempotencia  VARCHAR(64)    NOT NULL,
    motivo              VARCHAR(300)   NOT NULL,
    base_gravable       NUMERIC(14, 2) NOT NULL,
    impuestos           NUMERIC(14, 2) NOT NULL,
    total               NUMERIC(14, 2) NOT NULL,
    costo_total         NUMERIC(14, 2),
    registrada_por_id   BIGINT         NOT NULL,
    registrada_en       TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_devoluciones_venta PRIMARY KEY (id),
    CONSTRAINT uq_devoluciones_venta_clave UNIQUE (empresa_id, clave_idempotencia),
    CONSTRAINT uq_devoluciones_venta_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_devoluciones_venta_venta FOREIGN KEY (empresa_id, venta_id) REFERENCES ventas (empresa_id, id),
    CONSTRAINT fk_devoluciones_venta_usuario
        FOREIGN KEY (empresa_id, registrada_por_id) REFERENCES usuarios (empresa_id, id),
    CONSTRAINT ck_devoluciones_venta_tipo CHECK (tipo IN ('DEVOLUCION', 'ANULACION')),
    CONSTRAINT ck_devoluciones_venta_importes CHECK (
        base_gravable >= 0 AND impuestos >= 0 AND total = base_gravable + impuestos
        AND (costo_total IS NULL OR costo_total >= 0))
);

CREATE INDEX ix_devoluciones_venta_venta ON devoluciones_venta (empresa_id, venta_id);
CREATE INDEX ix_devoluciones_venta_fecha ON devoluciones_venta (empresa_id, registrada_en);

CREATE TABLE detalles_devolucion_venta (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    empresa_id            BIGINT         NOT NULL,
    devolucion_id         BIGINT         NOT NULL,
    detalle_venta_id      BIGINT         NOT NULL,
    cantidad              INTEGER        NOT NULL,
    reingresa_inventario  BOOLEAN        NOT NULL,
    base_gravable         NUMERIC(14, 2) NOT NULL,
    impuesto              NUMERIC(14, 2) NOT NULL,
    total                 NUMERIC(14, 2) NOT NULL,
    costo_unitario        NUMERIC(14, 4),

    CONSTRAINT pk_detalles_devolucion_venta PRIMARY KEY (id),
    CONSTRAINT uq_detalles_devolucion_venta_linea UNIQUE (devolucion_id, detalle_venta_id),
    CONSTRAINT uq_detalles_devolucion_venta_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_detalles_devolucion_venta_devolucion
        FOREIGN KEY (empresa_id, devolucion_id) REFERENCES devoluciones_venta (empresa_id, id),
    CONSTRAINT fk_detalles_devolucion_venta_detalle
        FOREIGN KEY (empresa_id, detalle_venta_id) REFERENCES detalles_venta (empresa_id, id),
    CONSTRAINT ck_detalles_devolucion_venta_cantidad CHECK (cantidad BETWEEN 1 AND 999999),
    CONSTRAINT ck_detalles_devolucion_venta_importes CHECK (
        base_gravable >= 0 AND impuesto >= 0 AND total = base_gravable + impuesto
        AND (costo_unitario IS NULL OR costo_unitario > 0))
);

-- ---------------------------------------------------------------------------
-- 10) Kárdex: salidas por venta (VENTA, con el costo promedio aplicado) y entradas por
--     devolución o anulación (DEVOLUCION_VENTA, con el costo histórico de la línea vendida).
-- ---------------------------------------------------------------------------
ALTER TABLE movimientos_inventario ADD COLUMN detalle_venta_id BIGINT;
ALTER TABLE movimientos_inventario ADD COLUMN detalle_devolucion_id BIGINT;
ALTER TABLE movimientos_inventario ADD CONSTRAINT uq_movimientos_inventario_detalle_venta UNIQUE (detalle_venta_id);
ALTER TABLE movimientos_inventario ADD CONSTRAINT uq_movimientos_inventario_detalle_devolucion
    UNIQUE (detalle_devolucion_id);
ALTER TABLE movimientos_inventario ADD CONSTRAINT fk_movimientos_inventario_detalle_venta
    FOREIGN KEY (empresa_id, detalle_venta_id) REFERENCES detalles_venta (empresa_id, id);
ALTER TABLE movimientos_inventario ADD CONSTRAINT fk_movimientos_inventario_detalle_devolucion
    FOREIGN KEY (empresa_id, detalle_devolucion_id) REFERENCES detalles_devolucion_venta (empresa_id, id);

ALTER TABLE movimientos_inventario DROP CONSTRAINT ck_movimientos_inventario_tipo;
ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_movimientos_inventario_tipo
    CHECK (tipo IN ('RECEPCION', 'AJUSTE', 'VENTA', 'DEVOLUCION_VENTA'));
ALTER TABLE movimientos_inventario DROP CONSTRAINT ck_movimientos_inventario_origen;
ALTER TABLE movimientos_inventario ADD CONSTRAINT ck_movimientos_inventario_origen CHECK (
    (tipo = 'RECEPCION' AND detalle_recepcion_id IS NOT NULL AND detalle_venta_id IS NULL
        AND detalle_devolucion_id IS NULL AND cantidad > 0 AND costo_unitario IS NOT NULL)
    OR (tipo = 'AJUSTE' AND detalle_recepcion_id IS NULL AND detalle_venta_id IS NULL
        AND detalle_devolucion_id IS NULL AND motivo IS NOT NULL AND clave_idempotencia IS NOT NULL)
    OR (tipo = 'VENTA' AND detalle_venta_id IS NOT NULL AND detalle_recepcion_id IS NULL
        AND detalle_devolucion_id IS NULL AND cantidad < 0)
    OR (tipo = 'DEVOLUCION_VENTA' AND detalle_devolucion_id IS NOT NULL AND detalle_recepcion_id IS NULL
        AND detalle_venta_id IS NULL AND cantidad > 0));

-- ---------------------------------------------------------------------------
-- 11) Costo promedio ponderado de las existencias (método provisional, pendiente de
--     validación contable). NULL = desconocido. V16 lo calcula a partir del kárdex existente.
-- ---------------------------------------------------------------------------
ALTER TABLE existencias ADD COLUMN costo_promedio NUMERIC(14, 4);
ALTER TABLE existencias ADD CONSTRAINT ck_existencias_costo_promedio CHECK (costo_promedio IS NULL OR costo_promedio > 0);
